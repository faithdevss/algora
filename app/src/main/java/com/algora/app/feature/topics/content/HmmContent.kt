                tags  = ["NN", "VB", "DT", "IN"]
                start = {"NN": .35, "VB": .25, "DT": .30, "IN": .10}
                A = {"NN": {"NN": .15, "VB": .30, "DT": .05, "IN": .30, "</s>": .20},
                     "VB": {"NN": .20, "VB": .05, "DT": .50, "IN": .10, "</s>": .15},
                     "DT": {"NN": .90, "VB": .02, "DT": .02, "IN": .02, "</s>": .04},
                     "IN": {"NN": .60, "VB": .05, "DT": .30, "IN": .03, "</s>": .02}}
                B = {"NN": {"book": .030, "flight": .020},
                     "VB": {"book": .040},
                     "DT": {"that": .150},
                     "IN": {"that": .250}}
                b = lambda t, w: B[t].get(w, 0.0)

                def viterbi(words):
                    v = {t: start[t] * b(t, words[0]) for t in tags}
                    back = []
                    for w in words[1:]:
                        step = {}
                        ptr = {}
                        for to in tags:
                            best = max(tags, key=lambda fr: v[fr] * A[fr][to])
                            ptr[to] = best
                            step[to] = v[best] * A[best][to] * b(to, w)
                        v, _ = step, back.append(ptr)
                    final = {t: p * A[t]["</s>"] for t, p in v.items()}
                    tag = max(final, key=final.get)
                    path = [tag]
                    for ptr in reversed(back):
                        tag = ptr[tag]
                        path.insert(0, tag)
                    return path, max(final.values())

                print(viterbi(["book", "that", "flight"]))   # (['VB', 'DT', 'NN'], 2.7e-06)

