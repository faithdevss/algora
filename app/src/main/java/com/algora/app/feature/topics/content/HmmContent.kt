        "The reason it is not just an n-gram model is the decoding problem. \"book that flight\" has two grammatical readings: VB DT NN (an instruction) and NN IN NN (\"book\" the object, \"that\" a complementiser). Tagging greedily left to right picks the locally best tag at each step — and here it opens with NN, because P(NN)·P(book|NN) = 0.0105 beats VB's 0.0100, then never revisits that choice. Viterbi keeps the best path *into every state* instead of one path overall, so the VB opening is still alive when the second word is scored, and the strong DT → NN transition pulls the whole sequence back to the imperative reading. It is 1.43× more probable than the answer greedy committed to.",
