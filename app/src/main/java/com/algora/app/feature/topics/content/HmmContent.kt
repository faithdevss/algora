                def logsumexp(xs):
                    m = max(xs)
                    return m + log(sum(exp(x - m) for x in xs)) if m > -inf else -inf

                def forward_log(words):
                    a = {t: (log(start[t]) + log(b(t, words[0]))) if b(t, words[0]) else -inf
